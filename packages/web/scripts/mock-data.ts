/** Board + signal metadata as the pipeline would publish it (mirrors the weights in `config.yaml`). */
export function boardMeta(): BoardMeta[] {
  return BOARDS.map((board) => {
    const [en, zh, subEn, subZh] = BOARD_TEXT[board]
    const meta: BoardMeta = {
      board,
      title: { en, zh },
      subtitle: { en: subEn, zh: subZh },
      size: 10,
      runnersUp: 10,
      signals: SIGNALS[board].map(([key, weight, cap, curve, labelEn, labelZh, helpEn, helpZh]) => ({
        key,
        weight,
        cap,
        curve,
        label: { en: labelEn, zh: labelZh },
        help: { en: helpEn, zh: helpZh },
      })),
    }
    if (board === 'labs') meta.lookbackDays = 7
    return meta
  })
}

